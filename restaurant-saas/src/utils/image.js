// Image helpers — the app stores images as compressed JPEG data URLs in
// Firestore instead of Firebase Storage, because Storage needs the paid
// Blaze plan and this project runs on the free Spark plan. A downscaled
// 800px JPEG (~80–200KB as a data URL) fits easily inside Firestore's
// 1MB document limit, and <img> renders a data URL directly.

export function downscaleImage(file, maxWidth = 800, quality = 0.72) {
  return new Promise((resolve, reject) => {
    const url = URL.createObjectURL(file);
    const img = new Image();
    img.onload = () => {
      try {
        const scale = Math.min(1, maxWidth / img.width);
        const w = Math.max(1, Math.round(img.width * scale));
        const h = Math.max(1, Math.round(img.height * scale));
        const canvas = document.createElement("canvas");
        canvas.width = w;
        canvas.height = h;
        canvas.getContext("2d").drawImage(img, 0, 0, w, h);
        URL.revokeObjectURL(url);
        resolve(canvas.toDataURL("image/jpeg", quality));
      } catch (e) {
        URL.revokeObjectURL(url);
        reject(e);
      }
    };
    img.onerror = () => {
      URL.revokeObjectURL(url);
      reject(new Error("Could not read image"));
    };
    img.src = url;
  });
}
